"""Generate controlled switch-dispatch experiments without changing the main benchmark."""

from paths import ARTIFACTS
import math
from itertools import islice

from generate import source as selection_source

OUT = ARTIFACTS / "diagnostic-generated"
COUNT = 2_000_000
SIZE = 64
INPUT_COUNT = 4096
PATTERNS = ("cycle", "fixed", "random")
OPERATIONS = ("value", "arithmetic", "call")
THRESHOLDS = (8, 16, 24, 32, 48, 64)


def indices(pattern):
    state = 1
    for i in range(1, COUNT + 1):
        if pattern == "cycle":
            yield (i * 73) % SIZE
        elif pattern == "fixed":
            yield 17
        else:
            state = (state * 1664525 + 1013904223) % 4294967296
            yield (state // 65536) % SIZE


def value(index, operation):
    if operation == "arithmetic":
        return index * 4
    if operation == "call":
        return math.floor(index / 3 + index)
    return index


def source(kind, pattern, operation, expected, inputs, size=SIZE):
    key = "value * 101" if kind == "tree" else "value"
    setup = "local inputs = {" + ", ".join(map(str, inputs)) + "}\n"
    if kind == "table":
        entries = ", ".join(f"[{i}] = {i}" for i in range(size))
        setup += f"local lookup = {{{entries}}}\n"

    if kind == "table":
        body = "        result = lookup[value] or -1"
        if operation == "arithmetic":
            body = "        result = value * 3 + (lookup[value] or -1)"
        if operation == "call":
            body = "        result = math.floor(value / 3 + (lookup[value] or -1))"
    elif kind == "baseline":
        expression = "value"
        if operation == "arithmetic":
            expression = "value * 3 + value"
        elif operation == "call":
            expression = "math.floor(value / 3 + value)"
        body = f"        result = {expression}"
    else:
        lines = [f"        switch {key}"]
        for i in range(size):
            expression = str(i)
            if operation == "arithmetic":
                expression = f"value * 3 + {i}"
            elif operation == "call":
                expression = f"math.floor(value / 3 + {i})"
            label = i * 101 if kind == "tree" else i
            lines.extend((f"            case {label} then", f"                result = {expression}"))
        lines.extend(("            else", "                result = -1", "        end"))
        body = "\n".join(lines)

    assignment = f"        local value = inputs[(i - 1) % {INPUT_COUNT} + 1]"
    name = f"{kind}-{operation}-{pattern}"
    if size != SIZE:
        name = f"{kind}-{size}-{operation}-{pattern}"
    return f'''-- Generated by bench/switch/diagnostic.py.
local function prequire(name) local ok, result = pcall(require, name); return ok and result end
local bench = script and require(script.Parent.Parent.bench_support) or prequire("bench_support") or require("../../bench_support")
{setup}local function test()
    local result = 0
    local checksum = 0
    for i = 1, {COUNT} do
{assignment}
{body}
        checksum += result
    end
    assert(checksum == {expected})
end
bench.runCode(test, "{name}")
'''


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.luau"):
        old.unlink()
    for pattern in PATTERNS:
        inputs = list(islice(indices(pattern), INPUT_COUNT))
        cycles, tail = divmod(COUNT, INPUT_COUNT)
        for operation in OPERATIONS:
            expected = cycles * sum(value(index, operation) for index in inputs)
            expected += sum(value(index, operation) for index in inputs[:tail])
            for kind in ("switch", "table", "tree", "baseline"):
                (OUT / f"{kind}-{operation}-{pattern}.luau").write_text(
                    source(kind, pattern, operation, expected, inputs), newline="\n"
                )
    for size in THRESHOLDS:
        (OUT / f"switch-threshold-{size}.luau").write_text(selection_source("switch", size), newline="\n")
    for size in (24, 32, 48):
        inputs = [(i * 73) % size for i in range(1, INPUT_COUNT + 1)]
        cycles, tail = divmod(COUNT, INPUT_COUNT)
        expected = cycles * sum(inputs) + sum(inputs[:tail])
        (OUT / f"tree-threshold-{size}.luau").write_text(
            source("tree", "cycle", "value", expected, inputs, size), newline="\n"
        )
    print(f"Generated 45 diagnostic benchmarks in {OUT}")
