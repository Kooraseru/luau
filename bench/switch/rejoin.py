"""Generate switch cases that either rejoin or return directly."""

from itertools import islice
from paths import ARTIFACTS

from diagnostic import COUNT, SIZE, INPUT_COUNT, indices, value

OUT = ARTIFACTS / "rejoin-generated"


def source(form, operation, pattern, expected, inputs):
    lines = ["    switch value"]
    for index in range(SIZE):
        expression = str(index)
        if operation == "arithmetic":
            expression = f"value * 3 + {index}"
        elif operation == "call":
            expression = f"math.floor(value / 3 + {index})"
        statement = f"return ({expression}) + offset" if form == "direct" else f"result = {expression}"
        lines.extend((f"        case {index} then", f"            {statement}"))
    fallback = "return -1 + offset" if form == "direct" else "result = -1"
    lines.extend(("        else", f"            {fallback}", "    end"))
    if form == "rejoin":
        lines.append("    return result + offset")
    dispatch = "\n".join(lines)

    assignment = f"local value = inputs[(i - 1) % {INPUT_COUNT} + 1]"

    name = f"{form}-{operation}-{pattern}"
    return f'''-- Generated by bench/switch/rejoin.py.
local function prequire(name) local ok, result = pcall(require, name); return ok and result end
local bench = script and require(script.Parent.Parent.bench_support) or prequire("bench_support") or require("../../bench_support")
local inputs = {{{", ".join(map(str, inputs))}}}
local function dispatch(value, offset)
    local result = 0
{dispatch}
end
local function test()
    local checksum = 0
    local offset = math.random(0, 0)
    for i = 1, {COUNT} do
        {assignment}
        checksum += dispatch(value, offset)
    end
    assert(checksum == {expected})
end
bench.runCode(test, "{name}")
'''


OUT.mkdir(parents=True, exist_ok=True)
for old in OUT.glob("*.luau"):
    old.unlink()
for pattern in ("cycle", "fixed", "random"):
    inputs = list(islice(indices(pattern), INPUT_COUNT))
    cycles, tail = divmod(COUNT, INPUT_COUNT)
    for operation in ("value", "arithmetic", "call"):
        expected = cycles * sum(value(index, operation) for index in inputs)
        expected += sum(value(index, operation) for index in inputs[:tail])
        for form in ("rejoin", "direct"):
            (OUT / f"{form}-{operation}-{pattern}.luau").write_text(
                source(form, operation, pattern, expected, inputs), newline="\n"
            )
print(f"Generated 18 rejoin benchmarks in {OUT}")
